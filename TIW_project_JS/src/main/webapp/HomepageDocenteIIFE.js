	function Verbali(options)
    { 	
		let self = this;
		
	    this.verbali_table = options['verbali_table'];
	    this.verbali_table_body = options['verbali_table_body'];
	    
	    this.reset = function()
	    {
			self.verbali_table.style.display = "none";
		}

	    this.show = function(appelloid)
	    {
	    	let address = URL_VERBALI + '?id_appello=' + appelloid;
	    	let verbaliToShow;
	    	let message;
	    	
	      	makeCall("GET", address, null,
	        	function(req)
	        	{
	          		if (req.readyState == XMLHttpRequest.DONE)
	          		{
	            		message = req.responseText;
			            if (req.status == 200)
			            {
				        	verbaliToShow = JSON.parse(message);
				        	
				        	if (verbaliToShow.length == 0)
			              	{
								self.reset();
			                	return;
			              	}
			              	else
			              	{
						    	self.update(verbaliToShow);
						    	self.verbali_table.style.display = "inline-table";
							}
			            }
			            else
			            	alert(req.responseText);
	          		}
				}
	      	);
	    };

	    this.update = function(verbaliToShow)
	    {
			let row;
		   
		   	emptyElementContent(self.verbali_table_body);
		    
		    verbaliToShow.forEach(function(verbale)
		    {
		        row = document.createElement("tr");
		        
		        createLinkTD(row, verbale.id, verbale.id, verbaleInfo)
		        createTD(row, verbale.datetime);
		        
		        self.verbali_table_body.appendChild(row);
	      	});
	    };
	}
	
