	window.addEventListener("load", () =>
	{
		// Security check for docente
		makeCall("GET", URL_DOCENTE, null,
		        // callback function
		        function(req)
		        {
			    	if (req.readyState == XMLHttpRequest.DONE) // == 4
			    	{
						let message = req.responseText;
			            if (req.status == 200) 
			            {
							// if everything is fine, setup page view
							docente = JSON.parse(message);
							pageOrchestrator.start(); 
						}
						else
			            {
							window.location.href = "index.html";
							return;
						}
			      	}
		        }
      		);
		
 	}, false);
		  
