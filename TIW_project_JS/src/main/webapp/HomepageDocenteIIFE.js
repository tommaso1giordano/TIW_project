	function InserimentoMultiplo(options)
	{	
		let self = this;
		
		this.modalDiv = options['modalDiv'];
		this.voto_mult = options['voto_mult'];
		this.assign_mult_button = options['assign_mult_button'];
		this.ins_mult_table = options['ins_mult_table'];
		this.ins_mult_table_body = options['ins_mult_table_body'];
		this.closeButton = options['closeButton'];
		
		// List of matricole checked for multiple assignment
		this.matricoleChecked = [];
		
		this.reset = function()
		{
			self.modalDiv.style.display = "none";
			self.voto_mult.value = "";
			self.matricoleChecked = [];
		}
		
		this.show = function(idAppello)
	    {
	    	let address = URL_ESAMI_BY_APPELLO + '?id_appello=' + idAppello + "&examState=Non_inserito";
	    	let esamiToShow;
	    	
	      	makeCall("GET", address, null,
	        	function(req)
	        	{
	          		if (req.readyState == XMLHttpRequest.DONE)
	          		{
	            		message = req.responseText;
			            if (req.status == 200)
			            {
				        	esamiToShow = JSON.parse(message);
				        	
				        	if (esamiToShow.length == 0)
			              	{
								alert("Non ci sono esami di cui fare inserimento multiplo.");
			              	}
			              	else
			              	{
						    	self.update(idAppello, esamiToShow); // self is the object on which the function
						    	self.modalDiv.style.display = "block";
							}
			            }
			            else
			            	alert(req.responseText);
	          		}
        		}
	      	);
  		}
  		
  		this.update = function(idAppello, esamiToShow)
	    {	
			emptyElementContent(self.ins_mult_table_body);
			self.voto_mult.value = ""; // empty the new grade field;
			
			self.modalDiv.setAttribute("attribute", idAppello);
			self.assign_mult_button.setAttribute("attribute", idAppello);
			self.closeButton.setAttribute("attribute", idAppello);
		   
		    esamiToShow.forEach(function(esameToShow)
		    { // self visible here, not this
		        row = document.createElement("tr");
		        
		        createTD(row, esameToShow.matricola_studente);
		        createCheckboxTD(row, esameToShow.matricola_studente, 
		        	function(key)
			        {
						key = parseInt(key);
						self.addMatricolaToAssign(key);
					}, 	function(key)
					{
						key = parseInt(key);
						self.removeMatricolaToAssign(key)
					});
		        
		        self.ins_mult_table_body.appendChild(row);
	      	});
	    };
	    
	    this.init = function()
		{
			self.createAssegnamentoMultiploBtnEvent();
			self.createCloseModalWindowBtnEvent();
			self.CreateClickOutsideModalWindowEvent();
		}
	    
	    this.createAssegnamentoMultiploBtnEvent = function()
		{
			this.assign_mult_button.addEventListener("click", (event) =>
			{
				event.preventDefault();
				
				let idAppello = event.target.getAttribute("attribute");
				
				let encodedMatricole = encodeURIComponent(JSON.stringify(self.matricoleChecked));
				
				let newVoto = self.voto_mult.value;
				
				let address = URL_ASSIGN_MULT_GRADE
					+ "?id_appello=" + idAppello
					+ "&matricole=" + encodedMatricole
					+ "&voto=" + newVoto;
				
				makeCall("GET", address, null,
	        	function(req)
		        	{
		          		if (req.readyState == XMLHttpRequest.DONE)
		          		{
		            		message = req.responseText;
		            		
		            		if (req.status == 200)
		            		{
								if(message == "Invalid grade")
					            {
									alert("Hai inserito un voto non valido.");
									pageOrchestrator.showInserimentoMultiplo(idAppello);
								}
								if(message == "No matricole selected")
								{
									alert("Non hai selezionato nessuna matricola.");
									pageOrchestrator.showInserimentoMultiplo(idAppello);
								}
					            else
					            {
						        	pageOrchestrator.showEsami(idAppello)
					            }
							}
							else
								alert(req.responseText);
		          		}
	        		}
	    		);
			}, false);
		}
		
		this.createCloseModalWindowBtnEvent = function()
		{
			// Defines behaviour of button close event
			this.closeButton.addEventListener("click", (event) =>
			{
				pageOrchestrator.showEsami(event.target.getAttribute("attribute"));
			}, false);
		}
  		
  		this.CreateClickOutsideModalWindowEvent = function()
  		{
		  	// Defines bevaviour when clicking outside the modal window
			window.onclick = function(event)
			{
				if (event.target == self.modalDiv)
				{
			    	pageOrchestrator.showEsami(event.target.getAttribute("attribute"));
			  	}
			}
		}
		
		// Adds matricola to list of ones for multiple assignment
		this.addMatricolaToAssign = function(matricola)
  		{
	    	self.matricoleChecked.push(matricola);
		}
		
		// Removes matricola to list of ones for multiple assignment
		this.removeMatricolaToAssign = function(matricola)
  		{
			self.matricoleChecked.pop(matricola);
	  	}
	}
